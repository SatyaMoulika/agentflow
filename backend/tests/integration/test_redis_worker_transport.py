@pytest.fixture
def redis_url() -> str:
    raw = os.environ.get("TEST_REDIS_URL", "")
    try:
        parsed = urlsplit(raw)
        valid = (
            parsed.scheme == "redis"
            and parsed.hostname in {"127.0.0.1", "localhost"}
            and parsed.port == 16380
            and parsed.path == "/15"
            and not parsed.query
            and not parsed.fragment
            and parsed.username is None
            and parsed.password is None
        )
    except ValueError:
        valid = False
    if not valid:
        pytest.fail(
            "Set TEST_REDIS_URL to the isolated local Redis test service on port 16380/database 15",
            pytrace=False,
        )
    return raw


@pytest.fixture
def queue(redis_url: str) -> Iterator[str]:
    name = f"agentflow.test.{uuid4().hex}"
    yield name
    # Delete only keys generated by this randomly named test queue, never FLUSHDB.
    client = Redis.from_url(redis_url)
    client.delete(
        name,
        *(name + "\x06\x16" + str(priority) for priority in (3, 6, 9)),
        f"_kombu.binding.{name}",
    )
    client.close()


def test_real_worker_consumes_no_payload_probe_and_shutdown(
    redis_url: str, queue: str, tmp_path: Path
) -> None:
    settings = Settings(redis_url=SecretStr(redis_url), worker_queue=queue)
    app = create_celery(settings)
    log_path = tmp_path / "worker.log"
    env = {
        key: value
        for key, value in os.environ.items()
        if not key.upper().startswith(("AGENTFLOW_", "CELERY_"))
    }
    env.update(
        AGENTFLOW_REDIS_URL=redis_url,
        AGENTFLOW_WORKER_QUEUE=queue,
        AGENTFLOW_ENVIRONMENT="testing",
        PYTHONUNBUFFERED="1",
    )
    bootstrap = (
        'from app.core.config import Settings; Settings.model_config["env_file"] = None; '
        "from app.workers.__main__ import main; raise SystemExit(main())"
    )
    with log_path.open("w+") as log:
        process = subprocess.Popen(
            [sys.executable, "-c", bootstrap], env=env, stdout=log, stderr=subprocess.STDOUT
        )
        try:
            for _ in range(150):
                assert process.poll() is None, "worker exited before readiness"
                log.flush()
                if " ready." in log_path.read_text():
                    break
                time.sleep(0.1)
            else:
                pytest.fail("Worker did not become ready")
            probe_id = publish_probe(app, queue)
            for _ in range(150):
                log.flush()
                lines = log_path.read_text().splitlines()
                found = []
                for line in lines:
                    try:
                        record = json.loads(line)
                    except (json.JSONDecodeError, ValueError):
                        continue
                    if record.get("message") == "Transport probe consumed":
                        found.append(record)
                if found:
                    break
                assert process.poll() is None, "worker exited before delivery"
                time.sleep(0.1)
            else:
                pytest.fail("Probe was not consumed")
            assert len(found) == 1 and found[0]["probe_id"] == str(probe_id)
            assert UUID(found[0]["probe_id"]) == probe_id
            client = Redis.from_url(redis_url)
            try:
                assert client.get(f"celery-task-meta-{probe_id}") is None
            finally:
                client.close()
        finally:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)
                pytest.fail("Worker did not shut down gracefully")
            app.close()
    assert process.returncode in (0, -15)


def test_unreachable_broker_fails_safely_and_without_long_retry(queue: str) -> None:
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", 0))
        port = listener.getsockname()[1]
        # Bound but not listening: no process can take the port during this test.
        app = create_celery(
            Settings(
                redis_url=SecretStr(f"redis://:private-password@127.0.0.1:{port}/15"),
                worker_queue=queue,
            )
        )
        try:
            start = time.monotonic()
            with pytest.raises(TransportUnavailableError) as failure:
                publish_probe(app, queue)
            assert time.monotonic() - start < 8
            assert "private-password" not in str(failure.value)
        finally:
            app.close()


def test_worker_startup_fails_without_leaking_broker_password(queue: str, tmp_path: Path) -> None:
    with socket.socket() as listener:
        listener.bind(("127.0.0.1", 0))
        port = listener.getsockname()[1]
        env = {
            key: value
            for key, value in os.environ.items()
            if not key.upper().startswith(("AGENTFLOW_", "CELERY_"))
        }
        env.update(
            AGENTFLOW_REDIS_URL=f"redis://:private-broker-password@127.0.0.1:{port}/15",
            AGENTFLOW_WORKER_QUEUE=queue,
            AGENTFLOW_ENVIRONMENT="testing",
            PYTHONUNBUFFERED="1",
        )
        bootstrap = (
            'from app.core.config import Settings; Settings.model_config["env_file"] = None; '
            "from app.workers.__main__ import main; raise SystemExit(main())"
        )
        with (tmp_path / "failure.log").open("w+") as log:
            try:
                process = subprocess.run(
                    [sys.executable, "-c", bootstrap],
                    env=env,
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    timeout=15,
                    check=False,
                )
            except subprocess.TimeoutExpired:
                pytest.fail("Worker startup did not fail within the expected bound")
        text = (tmp_path / "failure.log").read_text()
        assert process.returncode != 0
        assert "private-broker-password" not in text
